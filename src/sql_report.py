"""Run the named queries in sql/02 and sql/03 and write results/sql_report.md."""
from pathlib import Path
import re
import sqlite3

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "insurance.db"
FILES = ["02_data_quality.sql", "03_portfolio_analysis.sql"]


def named_queries(text):
    """Split a .sql file into (name, sql) pairs on '-- name:' lines."""
    parts = re.split(r"^-- name:\s*(.+)$", text, flags=re.M)
    return [(parts[i].strip(), parts[i + 1].strip()) for i in range(1, len(parts), 2)]


def main():
    con = sqlite3.connect(DB)
    out = ["# SQL report", "", "Generated by `src/sql_report.py` from the queries in `sql/`.", ""]
    for fname in FILES:
        out += [f"## {fname}", ""]
        for name, sql in named_queries((ROOT / "sql" / fname).read_text()):
            df = pd.read_sql(sql, con)
            out += [f"### {name}", "", df.to_markdown(index=False, floatfmt=",.4g"), ""]
            print(f"\n{name}\n{df.to_string(index=False)}")
    con.close()
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "sql_report.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
